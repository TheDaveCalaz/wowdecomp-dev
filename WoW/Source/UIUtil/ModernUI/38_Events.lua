		turnIn = { xp = GetRewardXP and GetRewardXP() or 0, money = GetRewardMoney and GetRewardMoney() or 0 }
	end,
	QUEST_FINISHED = function() if turnIn then turnIn.at = GetTime() end end,
	QUEST_LOG_UPDATE = function()
		local now = scanQuests()
		for id in pairs(questIDs) do
			if not now[id] then
				if turnIn and turnIn.at and GetTime() - turnIn.at < 5 then
					signal("QUEST_TURNED_IN", id, turnIn.xp, turnIn.money)
					turnIn = nil
				end
				signal("QUEST_REMOVED", id)
			end
		end
		questIDs = now
	end,
}
handlers.UNIT_AURA = function(unit)
	if unit == "player" then
		handlers.COMPANION_UPDATE()
	end
end

