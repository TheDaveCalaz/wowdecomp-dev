bridge:SetScript("OnEvent", function(_, event, ...)
	local handler = handlers[event]
	if handler then
		handler(...)
		return
	end
	local unit = ...
	local token = powerToken[event]
	if token then
		signal("UNIT_POWER_FREQUENT", unit, token)
		signal("UNIT_POWER_UPDATE", unit, token)
		return
	end
	token = maxPowerToken[event]
	if token then
		signal("UNIT_MAXPOWER", unit, token)
	end
end)

-- Group changes, movement, the mouse, and the deferred events, checked every frame.
local moving = false
local mouseButtons = { "LeftButton", "RightButton", "MiddleButton", "Button4", "Button5" }
local mouseDown = {}
local itemWaiting = {} -- itemID -> true while its data is not yet in the client
local waitTimer = 0
bridge:SetScript("OnUpdate", function(_, elapsed)
	for event, args in pairs(pending) do
		pending[event] = nil
		if event == "GROUP_ROSTER_UPDATE" then
			local now = (GetNumRaidMembers() > 0 or GetNumPartyMembers() > 0)
			if now ~= inGroup then
				inGroup = now
				signal(now and "GROUP_JOINED" or "GROUP_LEFT", 1)
			end
		end
		if args == true then
			signal(event)
		else
			signal(event, unpack(args))
		end
	end

	local speed = GetUnitSpeed and GetUnitSpeed("player") or 0
	local nowMoving = speed > 0
	if nowMoving ~= moving then
		moving = nowMoving
		signal(moving and "PLAYER_STARTED_MOVING" or "PLAYER_STOPPED_MOVING")
	end

	if IsMouseButtonDown then
		for _, button in ipairs(mouseButtons) do
			local down = IsMouseButtonDown(button) and true or false
			if down ~= (mouseDown[button] or false) then
				mouseDown[button] = down
				signal(down and "GLOBAL_MOUSE_DOWN" or "GLOBAL_MOUSE_UP", button)
			end
		end
	end

	waitTimer = waitTimer + elapsed
	if waitTimer > 0.2 and next(itemWaiting) then
		waitTimer = 0
		for itemID in pairs(itemWaiting) do
			if GetItemInfo(itemID) then
				itemWaiting[itemID] = nil
				signal("GET_ITEM_INFO_RECEIVED", itemID, true)
				signal("ITEM_DATA_LOAD_RESULT", itemID, true)
			end
		end
	end
end)

-- Data requests: items arrive from the server (watched above); spells and quests are already here.
local function itemIDOf(item)
	if type(item) == "number" then
		return item
	end
	if type(item) == "string" then
		return tonumber(match(item, "item:(%d+)")) or tonumber(item)
	end
end
local function watchItem(item)
	local id = itemIDOf(item)
	if id and not GetItemInfo(id) then
		itemWaiting[id] = true
	end
end
do
	local GetItemInfo_global = GetItemInfo
	local function noteMissing(item, name, ...)
		if name == nil and item ~= nil then
			local id = itemIDOf(item)
			if id then
				itemWaiting[id] = true
			end
		end
		return name, ...
	end
	GetItemInfo = function(item, ...)
		return noteMissing(item, GetItemInfo_global(item, ...))
	end
end
local C_Item = _G.C_Item
if C_Item then
	local request = C_Item.RequestLoadItemDataByID
	C_Item.RequestLoadItemDataByID = function(item, ...)
		watchItem(item)
		if request then
			return request(item, ...)
		end
	end
end
local C_Spell = _G.C_Spell
if C_Spell then
	C_Spell.RequestLoadSpellData = function(spellID)
		later("SPELL_DATA_LOAD_RESULT", spellID, true)
	end
end
local C_QuestLog = _G.C_QuestLog
if C_QuestLog then
	C_QuestLog.RequestLoadQuestByID = function(questID)
		later("QUEST_DATA_LOAD_RESULT", questID, true)
	end
end

