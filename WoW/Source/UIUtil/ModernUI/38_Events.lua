-- Casts: modern events carry a cast GUID ("Cast-3-...-<spellID>-<counter>") and the spell ID instead of the
-- spell's name and rank. One GUID per cast and unit, so the start and end of a cast match.
local castCounter = 0
local castOf = {}
local function newCast(unit, spellID)
	castCounter = castCounter + 1
	local guid = format("Cast-3-1-0-0-%d-%010X", spellID or 0, castCounter)
	castOf[unit] = guid
	return guid
end
local function currentCast(unit, spellID)
	return castOf[unit] or newCast(unit, spellID)
end
local startsCast = { UNIT_SPELLCAST_START = true, UNIT_SPELLCAST_CHANNEL_START = true }
local spellcast = {
	UNIT_SPELLCAST_START = true, UNIT_SPELLCAST_STOP = true, UNIT_SPELLCAST_FAILED = true,
	UNIT_SPELLCAST_FAILED_QUIET = true, UNIT_SPELLCAST_INTERRUPTED = true, UNIT_SPELLCAST_DELAYED = true,
	UNIT_SPELLCAST_SUCCEEDED = true, UNIT_SPELLCAST_CHANNEL_START = true, UNIT_SPELLCAST_CHANNEL_STOP = true,
	UNIT_SPELLCAST_CHANNEL_UPDATE = true, UNIT_SPELLCAST_INTERRUPTIBLE = true, UNIT_SPELLCAST_NOT_INTERRUPTIBLE = true,
}

local function questIDAt(index)
	local link = index and GetQuestLink and GetQuestLink(index)
	return link and tonumber(match(link, "quest:(%d+)")) or 0
end

local fullAuraUpdate = { isFullUpdate = true }

function ModernUI_ReshapeEvent(event, ...)
	if spellcast[event] then
		local unit, _, _, _, spellID = ...
		local guid = startsCast[event] and newCast(unit, spellID) or currentCast(unit, spellID)
		if event == "UNIT_SPELLCAST_INTERRUPTED" or event == "UNIT_SPELLCAST_CHANNEL_STOP" then
			return event, unit, guid, spellID, nil, 0
		end
		return event, unit, guid, spellID, 0
	elseif event == "UNIT_SPELLCAST_SENT" then
		local unit, _, _, target, spellID = ...
		return event, unit, target, newCast(unit, spellID), spellID
	elseif event == "UNIT_AURA" then
		return event, (...), fullAuraUpdate
	elseif event == "QUEST_ACCEPTED" then
		local index = ...
		return event, index, questIDAt(index)
	elseif event == "COMBAT_LOG_EVENT_UNFILTERED" or event == "COMBAT_LOG_EVENT" then
		return event -- modern handlers read the event with CombatLogGetCurrentEventInfo()
	end
end

