-- Script objects (35_Objects.lua) and object answers of the generated surface.
-- Usage: python3 run.py test_objects.lua
local f = assert(loadstring(assert(io.open("../95_ApiSurface.lua")):read("*a"), "95_ApiSurface.lua"))
assert(pcall(f))
local function near(a, b) return math.abs(a - b) < 1e-6 end

local curve = C_CurveUtil.CreateCurve()
curve:AddPoint(0, 0)
curve:AddPoint(1, 10)
assert(near(curve:Evaluate(0.5), 5) and near(curve:Evaluate(2), 10) and near(curve:Evaluate(-1), 0), "linear curve")
curve:SetType(Enum.LuaCurveType.Step)
assert(near(curve:Evaluate(0.5), 0), "step curve")
assert(curve:GetPointCount() == 2 and curve:Copy():GetPointCount() == 2, "points and copy")
print("ok   curves")

local colors = C_CurveUtil.CreateColorCurve()
colors:AddPoint(0, CreateColor(1, 0, 0, 1))
colors:AddPoint(1, CreateColor(0, 1, 0, 1))
local r, g = colors:EvaluateUnpacked(0.5)
assert(near(r, 0.5) and near(g, 0.5), "colour curve")
assert(colors:Evaluate(1).g == 1, "colour curve returns a colour")
print("ok   colour curves")

local d = C_DurationUtil.CreateDuration()
local clock = C_DurationUtil.CreateManualClock()
d:SetClock(clock)
d:SetTimeFromStart(10, 20, 1)
clock:SetTime(15)
assert(near(d:GetRemainingDuration(), 15) and near(d:GetElapsedPercent(), 0.25) and d:IsActive(), "duration")
clock:SetTime(40)
assert(d:HasExpired() and not d:IsActive(), "expired duration")
print("ok   durations")

assert(AbbreviateNumbers(1500) == "1.5K", AbbreviateNumbers(1500))
assert(AbbreviateNumbers(25000) == "25K", AbbreviateNumbers(25000))
assert(AbbreviateNumbers(950) == "950")
local config = CreateAbbreviateConfig({ { breakpoint = 1000, abbreviation = "k", significandDivisor = 1000, fractionDivisor = 1 } })
assert(AbbreviateNumbers(4200, { config = config }) == "4k", "custom breakpoints")
local formatter = C_StringUtil.CreateAbbreviatedNumberFormatter()
assert(formatter:FormatNumber(2500) == "2.5K", formatter:FormatNumber(2500))
assert(C_StringUtil.CreateSecondsFormatter():Format(3725) == "1h 2m")
print("ok   number formatting")

local obj = C_Intl.CreateLocaleContext("enUS")
assert(type(obj) == "table" and type(obj.FormatNumber) == "function", "documented object types have their methods")
assert(obj:FormatNumber(5) == "", "documented methods answer empty")
local cd = C_Spell.GetSpellCooldownDuration and C_Spell.GetSpellCooldownDuration(1)
assert(cd == nil or (cd.IsZero and cd:IsZero()), "a duration answer is an empty duration")
print("ok   object answers")
