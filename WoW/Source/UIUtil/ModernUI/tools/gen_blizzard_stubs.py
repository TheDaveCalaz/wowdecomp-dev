# Builds 97_BlizzardFunctionStubs.lua: the global functions Blizzard's Wrath Classic and retail interface code
# defines (CompactUnitFrame_UpdateAll, DefaultCompactUnitFrameSetup, ...) that this client's own interface never
# had. AddOns hook them (hooksecurefunc), key tables by them or call them; with nothing there each of those is an
# error that stops the AddOn's file. Each becomes a function that does nothing, set only where nothing exists,
# and only names the 3.3.5 interface does not define anywhere (its load-on-demand parts included).
# Usage: python3 gen_blizzard_stubs.py <out.lua> <3.3.5 api json> <Interface/AddOns dir> [<Interface/AddOns dir>...]
import re, glob, os, sys, json
api = json.load(open(sys.argv[2]))
ui335 = set(api.get('ui_globals', [])) | set(api.get('functions', [])) | set(api.get('ui_frames', []))
names = set()
for root in sys.argv[3:]:
    for f in glob.glob(root + '/**/*.lua', recursive=True):
        low = f.lower()
        if 'apidocumentation' in low or 'glue' in low or 'blizzard_secure' in low:
            continue
        text = open(f, encoding='utf-8', errors='replace').read()
        names.update(re.findall(r'^function\s+([A-Za-z_]\w*)\s*\(', text, re.M))
stubs = sorted(n for n in names if n not in ui335)
out = ['-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by tools/gen_blizzard_stubs.py.',
       "-- Global functions of Blizzard's Wrath Classic and retail interface that the 3.3.5 interface never had,",
       '-- as functions that do nothing, so AddOns that hook, call or key tables by them keep loading. Anything',
       '-- that already exists (the client, ModernUI, the imported Blizzard code) is left as it is.', '', 'local LIST = {']
line = ''
for n in stubs:
    item = '"%s",' % n
    if len(line) + len(item) > 112:
        out.append(line)
        line = ''
    line += item
out += [line, '}', 'local function nothing() end', 'for _, name in ipairs(LIST) do',
        '\tif rawget(_G, name) == nil then', '\t\t_G[name] = nothing', '\tend', 'end', '']
open(sys.argv[1], 'w').write('\n'.join(out))
print(len(stubs), 'stubs of', len(names), 'functions')
