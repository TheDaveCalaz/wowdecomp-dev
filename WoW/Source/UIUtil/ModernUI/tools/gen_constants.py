# Builds 12_BlizzardConstants.lua: the plain constants (NAME = number / "string" / true / false) that Blizzard's
# retail and Wrath Classic UI code sets at the top level of its files (BASE_MOVEMENT_SPEED = 7 and the like),
# which AddOns read as globals. Only names nothing else defines are set, so this client's own values win.
# Usage: python3 gen_constants.py <out.lua> <Interface/AddOns dir> [<Interface/AddOns dir>...]
import re, glob, os, sys
line = re.compile(r'^([A-Z][A-Z0-9_]{2,})\s*=\s*(-?\d+(?:\.\d+)?|"[^"\\\n]*"|true|false)\s*;?\s*(?:--.*)?$')
values, conflict = {}, set()
for root in sys.argv[2:]:
    for f in sorted(glob.glob(root + '/**/*.lua', recursive=True)):
        if 'APIDocumentation' in f or 'GlueXML' in f or 'Glue' in os.path.basename(os.path.dirname(f)):
            continue
        for text in open(f, encoding='utf-8', errors='replace'):
            m = line.match(text.rstrip('\r\n'))
            if m:
                name, value = m.groups()
                if name in values and values[name] != value:
                    conflict.add(name)
                values.setdefault(name, value)
out = ['-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by tools/gen_constants.py.',
       "-- Plain constants Blizzard's UI code sets at the top level of its files, which AddOns read as globals.",
       '-- Each is set only when nothing has defined it (the first client listed wins where they differ).',
       '', 'local K = {']
for name in sorted(values):
    out.append('%s=%s,' % (name, values[name]))
out += ['}', 'for name, value in pairs(K) do', '\tif rawget(_G, name) == nil then', '\t\t_G[name] = value', '\tend', 'end', '']
open(sys.argv[1], 'w').write('\n'.join(out))
print(len(values), 'constants,', len(conflict), 'differ between files')
