# Builds 11_EnumUndocumented.lua: the Enum tables that Blizzard's own UI code (and AddOns) read but that the API
# documentation does not list (Enum.GameRule and the like come from game data). Each gets the field names the
# code uses, numbered in order, so `Enum.GameRule.HardcoreRuleset` is a value rather than an error.
# Usage: python3 gen_enum_undoc.py <out.lua> <Lua source dir> [<Lua source dir>...]
import re, glob, os, sys, collections
MUI = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
have = set(re.findall(r'enum\("(\w+)"', open(MUI + '/10_Enum.lua').read()))
s = open(MUI + '/95_ApiSurface.lua').read()
have |= set(re.findall(r'^(\w+)=\{', s[s.index('local E = {'):s.index('local C = {')], re.M))
for f in glob.glob(MUI + '/*.lua'):
    if not os.path.basename(f).startswith('11_'):
        have |= set(re.findall(r'\bEnum\.(\w+)\s*=', open(f, errors='replace').read()))
use = collections.defaultdict(set)
for root in sys.argv[2:]:
    for f in glob.glob(root + '/**/*.lua', recursive=True):
        t = open(f, errors='replace').read()
        for a, b in re.findall(r'\bEnum\.(\w+)\.(\w+)', t):
            use[a].add(b)
        for a in re.findall(r'\bEnum\.(\w+)\b', t):
            use[a]
out = ['-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by tools/gen_enum_undoc.py.',
       "-- Enum tables that modern UI code reads but Blizzard's API documentation does not list (they come from game",
       '-- data). Each has the fields the code uses, numbered in order; nothing already defined is replaced.',
       '', 'local Enum = _G.Enum or {}', '_G.Enum = Enum', 'local U = {']
for name in sorted(k for k in use if k not in have):
    fields = sorted(f for f in use[name] if f not in ('MinValue', 'MaxValue', 'NumValues'))
    items = ['%s=%d' % (f, i) for i, f in enumerate(fields)]
    meta = use[name]
    if 'MinValue' in meta: items.append('MinValue=0')
    if 'MaxValue' in meta: items.append('MaxValue=%d' % max(len(fields) - 1, 0))
    if 'NumValues' in meta: items.append('NumValues=%d' % len(fields))
    out.append('%s={%s},' % (name, ','.join(items)))
out += ['}', 'for name, fields in pairs(U) do', '\tlocal t = rawget(Enum, name)', '\tif t == nil then',
        '\t\tt = {}', '\t\tEnum[name] = t', '\tend', '\tfor k, v in pairs(fields) do', '\t\tif rawget(t, k) == nil then',
        '\t\t\tt[k] = v', '\t\tend', '\tend', 'end', '']
open(sys.argv[1], 'w').write('\n'.join(out))
print(sum(1 for k in use if k not in have), 'enums')
