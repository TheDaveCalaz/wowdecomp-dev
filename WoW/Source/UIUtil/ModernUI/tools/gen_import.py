# Builds 96_BlizzardShared.lua: Blizzard's shared Lua code (Blizzard_SharedXMLBase, in .toc order), embedded
# as strings and run by the importer at the end of the file. Usage:
#   python3 gen_import.py <Interface/AddOns dir> <out.lua> <AddOn> [<AddOn>...]
# An AddOn written retail:<AddOn> (or retail:<AddOn>/<File>.toc) is read from the retail client's AddOns
# directory, given as RETAIL_ADDONS in the environment, as the retail client loads it ([Family] = Mainline,
# lines for other game types skipped). It comes after the Wrath Classic code, so it only adds what that lacks.
import os, re, sys
src, out = sys.argv[1], sys.argv[2]
parts = []
seen = set()
retail_src = os.environ.get('RETAIL_ADDONS')
for spec in sys.argv[3:]:
    # An AddOn name (its .toc) or AddOn/File.toc for a flavour's .toc.
    root, family, gametype = src, 'Classic', 'classic'
    if spec.startswith('retail:'):
        spec = spec[len('retail:'):]
        root, family, gametype = retail_src, 'Mainline', 'mainline'
    if spec.endswith('.lua'):
        # One file of an AddOn, on its own.
        addon = spec.split('/')[0]
        path = os.path.join(root, spec)
        if os.path.exists(path) and path not in seen:
            seen.add(path)
            text = open(path, encoding='utf-8-sig').read().replace('\r', '')
            level = 0
            while (']' + '=' * level + ']') in text:
                level += 1
            eq = '=' * level
            parts.append('{ %r, [%s[\n%s]%s] },' % (spec.replace('/', '\\'), eq, text, eq))
        continue
    if spec.endswith('.toc'):
        addon = spec.split('/')[0]
        toc = os.path.join(root, spec)
    else:
        addon = spec
        toc = os.path.join(root, addon, addon + '.toc')
    def add_lua(path, label):
        if not os.path.exists(path) or path in seen:
            return
        seen.add(path)
        text = open(path, encoding='utf-8-sig').read().replace('\r', '')
        level = 0
        while (']' + '=' * level + ']') in text:
            level += 1
        eq = '=' * level
        parts.append('{ %r, [%s[\n%s]%s] },' % (label, eq, text, eq))
    def add_xml(path):
        # Lua that an XML file pulls in with <Script file=...> and <Include file=...>, in order.
        if not os.path.exists(path) or path in seen:
            return
        seen.add(path)
        base = os.path.dirname(path)
        text = open(path, encoding='utf-8-sig', errors='replace').read()
        for kind, name in re.findall(r'<(Script|Include)\s+file="([^"]+)"', text):
            child = os.path.normpath(os.path.join(base, name.replace('\\', '/')))
            if kind == 'Script':
                add_lua(child, os.path.relpath(child, root).replace('/', '\\'))
            else:
                add_xml(child)
    for line in open(toc, encoding='utf-8-sig'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        allowed = re.search(r'\[AllowLoadGameType\s+([^\]]+)\]', line)
        if allowed and gametype not in [g.strip() for g in allowed.group(1).split(',')]:
            continue
        line = re.sub(r'\s*\[[^\]]*\]\s*$', '', line.replace('[Family]', family)).strip()
        path = os.path.join(root, addon, line.replace('\\', '/'))
        if line.lower().endswith('.lua'):
            add_lua(path, addon + '\\' + line)
        elif line.lower().endswith('.xml'):
            add_xml(path)
runtime = open(os.path.join(os.path.dirname(__file__), 'import_runtime.lua')).read()
with open(out, 'w') as f:
    f.write('-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by tools/gen_import.py.\n')
    f.write("-- Blizzard's shared Lua code from the Wrath Classic client and, after it, the retail client (" + ', '.join(sys.argv[3:]) + '), run in an environment\n')
    f.write('-- of its own; whatever it defines that this client and the hand-written ModernUI files lack becomes\n')
    f.write('-- global. Nothing that already exists is replaced.\n\n')
    f.write('local sources = {\n' + '\n'.join(parts) + '\n}\n\n' + runtime)
print(len(parts), 'files')
