# Builds 35_ModernFrameNames.lua: the names of Blizzard frames in the Wrath Classic and retail interfaces that the
# 3.3.5 interface does not have (StatusTrackingBarManager, BagsBar, EmbeddedItemTooltip, ...), with each frame's
# type. 36_FrameAliases.lua makes a hidden stand-in for one the first time code looks it up, so AddOns that hide,
# reparent or skin those frames carry on.
# Usage: python3 gen_modern_frames.py <out.lua> <3.3.5 api json> <Interface/AddOns dir> [<Interface/AddOns dir>...]
import re, glob, sys, json
api = json.load(open(sys.argv[2]))
ui335 = set(api.get('ui_globals', [])) | set(api.get('functions', [])) | set(api.get('ui_frames', [])) | set(api.get('ui_templates', []))
kinds = {}
tag = re.compile(r'<(Frame|Button|CheckButton|StatusBar|ScrollFrame|EditBox|Slider|GameTooltip|Cooldown|PlayerModel|DressUpModel|ModelScene|MessageFrame|ScrollingMessageFrame|SimpleHTML|ColorSelect|Model)\b([^>]*)>')
for root in sys.argv[3:]:
    for f in glob.glob(root + '/**/*.xml', recursive=True):
        low = f.lower()
        if 'glue' in low:
            continue
        for kind, attrs in tag.findall(open(f, encoding='utf-8', errors='replace').read()):
            if re.search(r'\bvirtual\s*=\s*"true"', attrs):
                continue
            m = re.search(r'\bname\s*=\s*"([A-Za-z_]\w*)"', attrs)
            if m:
                kinds.setdefault(m.group(1), 'GameTooltip' if kind == 'GameTooltip' else 'Frame' if kind in ('ModelScene', 'Model', 'PlayerModel', 'DressUpModel') else kind)
names = sorted(n for n in kinds if n not in ui335)
out = ['-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by tools/gen_modern_frames.py.',
       "-- Blizzard frames of the Wrath Classic and retail interfaces that the 3.3.5 interface does not have, and",
       '-- their types (see 36_FrameAliases.lua; this file loads first).', '', 'ModernUI_ModernFrameNames = {']
line = ''
for n in names:
    item = '%s="%s",' % (n, kinds[n])
    if len(line) + len(item) > 112:
        out.append(line)
        line = ''
    line += item
out += [line, '}', '']
open(sys.argv[1], 'w').write('\n'.join(out))
print(len(names), 'frames')
