# Builds 13_RetailOnlyNamespaces.lua: the C_ namespaces in the retail API documentation that the Wrath Classic
# documentation does not have. AddOns written for Classic clients as well do not see them (98_AddOnEnvironment.lua).
# A namespace Classic clients have but leave out of their documentation is kept, when Blizzard's Wrath Classic code is
# given: one whose functions that code calls are mostly ones retail's code never calls (C_LootHistory.GetItem and
# GetNumItems are the Classic loot history; retail rebuilt the system). A namespace whose Classic calls are the
# retail functions (C_Garrison in left-over quest reward code) stays retail-only.
# Usage: python3 gen_retail_only.py <out.lua> <Wrath Classic doc dir> <retail doc dir>
#        [<Wrath Classic Interface/AddOns dir> <retail Interface/AddOns dir>]
import glob, re, sys
def namespaces(d):
    out = set()
    for f in glob.glob(d + '/*.lua'):
        m = re.search(r'Namespace\s*=\s*"(\w+)"', open(f, errors='ignore').read())
        if m:
            out.add(m.group(1))
    return out
only = sorted(n for n in namespaces(sys.argv[3]) - namespaces(sys.argv[2]) if n.startswith('C_'))

def calls(d, names):
    out = {n: set() for n in names}
    pat = re.compile(r'\b(' + '|'.join(names) + r')\.(\w+)')
    for f in glob.glob(d + '/**/*.lua', recursive=True):
        if 'APIDocumentation' in f:
            continue
        for ns, fn in pat.findall(open(f, errors='ignore').read()):
            out[ns].add(fn)
    return out

if len(sys.argv) > 5 and only:
    classic, retail = calls(sys.argv[4], only), calls(sys.argv[5], only)
    kept = [n for n in only if classic[n] and len(classic[n] - retail[n]) * 2 > len(classic[n])]
    if kept:
        print('Classic has its own', ', '.join(kept))
    only = [n for n in only if n not in kept]
lines = ['-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by tools/gen_retail_only.py from the',
         "-- API documentation of the Wrath Classic (3.80) and retail (12.1) clients: the C_ namespaces only retail clients",
         '-- have. AddOns written for Classic clients as well do not see them (98_AddOnEnvironment.lua).', '',
         'ModernUI_RetailOnlyNamespaces = {']
line = ''
for n in only:
    item = '%s=true,' % n
    if len(line) + len(item) > 112:
        lines.append(line)
        line = ''
    line += item
lines += [line, '}', '']
open(sys.argv[1], 'w').write('\n'.join(lines))
print(len(only), 'namespaces')
