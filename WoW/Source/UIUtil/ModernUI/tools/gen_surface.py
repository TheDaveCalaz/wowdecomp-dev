import glob, sys, re
from lupa import lua51
# The documentation directory can be several, joined with ':' (Wrath Classic first, then retail): the first
# to document a function, enum value or constant decides it, the later ones add what the earlier lack.
DIRS=sys.argv[1].split(':'); D=DIRS[0]; OUT=sys.argv[2]
L=lua51.LuaRuntime(unpack_returned_tuples=True)
L.execute('docs = {} APIDocumentation = { AddDocumentationTable = function(self, t) docs[#docs+1] = t end }')
# Some documentation files compute values from Enum (Value = Enum.X.A + Enum.X.B); with no Enum they fail to load
# and everything they document is lost. Their enums are filled in as the files load; anything else reads 0.
L.execute('Enum = setmetatable({}, { __index = function(t, k) local v = setmetatable({}, { __index = function() return 0 end }) rawset(t, k, v) return v end })')
L.execute('local add = APIDocumentation.AddDocumentationTable; APIDocumentation.AddDocumentationTable = function(self, t) for _, tb in ipairs(t.Tables or {}) do if tb.Type == "Enumeration" then local e = rawget(Enum, tb.Name) or setmetatable({}, { __index = function() return 0 end }) rawset(Enum, tb.Name, e) for _, f in ipairs(tb.Fields or {}) do rawset(e, f.Name, f.EnumValue) end end end add(self, t) end')
for d in DIRS:
    for f in sorted(glob.glob(d+'/*.lua')):
        L.execute('local f=loadstring(...) if f then pcall(f) end', open(f,encoding='utf-8',errors='ignore').read())
docs=L.eval('docs')
def lst(t):
    return [t[i] for i in range(1,len(t)+1)] if t else []
enums={}; structs=set(); consts={}; objects=set()
for t in lst(docs):
    if t['Type']=='ScriptObject': objects.add(t['Name'])
for t in lst(docs):
    for tb in lst(t['Tables']):
        if tb['Type']=='Enumeration':
            have=enums.setdefault(tb['Name'],[])
            names={n for n,_ in have}
            have.extend((f['Name'],f['EnumValue']) for f in lst(tb['Fields']) if f['Name'] not in names)
        elif tb['Type']=='Structure':
            structs.add(tb['Name'])
        elif tb['Type']=='Constants':
            have=consts.setdefault(tb['Name'],[])
            names={n for n,_ in have}
            have.extend((v['Name'],v['Value']) for v in lst(tb['Values']) if v['Name'] not in names)
def objtype(ty):
    # A documented non-widget object type (a curve, a duration, a formatter): answered with an object that
    # has the documented methods, so code that builds one and calls its methods keeps working.
    if not ty or ty.startswith('Simple') or ty.startswith('Frame'): return None
    if ty+'API' in objects or ty+'ObjectAPI' in objects: return ty
    return None
def kind(r):
    ty=r['Type'] or ''
    if objtype(ty) and not r['Nilable']: return '{'+ty+'}'
    if r['Nilable']: return 'n'
    if ty=='bool': return 'b'
    if ty=='table' or ty in structs or r['InnerType']: return 't'
    if ty in enums: return '0'
    low=ty.lower()
    if 'string' in low or 'atlas' in low or low in ('wowguid','guid'): return 's'
    if low in ('number','luaindex','time_t','size','fileid','uimapid','bigint','bigufloat','biginteger','singlenumber','uidisplayindex','unknown') or low.endswith('id') or 'int' in low or 'float' in low or 'number' in low or 'time' in low or 'index' in low or 'count' in low:
        return '0'
    if low in ('uiunit','uifontheight','normalizedvalue','singlecolorvalue','tbfflags','wowmoney','soundhandle') or low.startswith('duration') and 'primitive' in low or low in ('durationseconds','durationsecondsdouble'):
        return '0'
    if low in ('justifyhorizontal','justifyvertical','drawlayer','framestrata','orientation','simplebuttonstatetoken'): return 's'
    if low in ('colorrgb','colorrgba'): return 'c'
    if low == 'vector2': return 'v'
    if low == 'vector3': return 'w'
    if low in ('uirect','lfgroles'): return 't'
    if 'mixin' in low or 'function' in low or 'callback' in low: return 'n'
    return 'n'
funcs=[]; methods=[]; done=set()
for t in lst(docs):
    ns=t['Namespace']; typ=t['Type']
    for fn in lst(t['Functions']):
        rets=''.join(kind(r) for r in lst(fn['Returns']))
        key=(typ=='ScriptObject', t['Name'] if typ=='ScriptObject' else (ns or ''), fn['Name'])
        if key in done: continue
        done.add(key)
        if typ=='ScriptObject': methods.append((t['Name'],fn['Name'],rets))
        else: funcs.append((ns or '',fn['Name'],rets))
def q(s): return '"'+str(s).replace('\\','\\\\').replace('"','\\"')+'"'
out=[]
out.append('-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by gen_surface.py from')
out.append("-- Blizzard's API documentation: the Wrath Classic client (3.80.2.70372) first, then the retail client for what it lacks.")
out.append('-- Do not edit by hand: hand-written implementations live in the other ModernUI files and always win.')
out.append('--')
out.append('-- Fills in every documented function, widget method, enum value and constant this client still lacks,')
out.append('-- so any AddOn written for the modern client finds the whole API. A filled-in function answers with an')
out.append('-- empty result of the documented type (no data, false, 0, an empty table): the answer of a client in')
out.append('-- which that game system has nothing to report.')
out.append('')
out.append('local F = {')
for ns,name,rets in funcs: out.append('%s,%s,%s,'%(q(ns),q(name),q(rets)))
out.append('}')
out.append('local M = {')
for g,name,rets in methods: out.append('%s,%s,%s,'%(q(g),q(name),q(rets)))
out.append('}')
out.append('local E = {')
for name,fields in sorted(enums.items()):
    out.append('%s={%s},'%(name, ','.join('%s=%s'%(f if re.match(r'^[A-Za-z_]\w*$',f) else '['+q(f)+']', v) for f,v in fields)))
out.append('}')
out.append('local C = {')
for name,vals in sorted(consts.items()):
    items=[]
    for k,v in vals:
        if isinstance(v,(int,float)): items.append('%s=%s'%(k,v))
        elif isinstance(v,str): items.append('%s=%s'%(k,q(v)))
        elif isinstance(v,bool): items.append('%s=%s'%(k,'true' if v else 'false'))
    out.append('%s={%s},'%(name,','.join(items)))
out.append('}')
out.append(open(sys.argv[3]).read())
open(OUT,'w').write('\n'.join(out)+'\n')
print(len(funcs),'functions',len(methods),'methods',len(enums),'enums',len(consts),'constant groups')
