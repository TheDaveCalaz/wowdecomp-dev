# Builds 91_BlizzardTemplates.xml: Blizzard's shared XML (fonts, font styles and virtual templates) from the
# Wrath Classic client, with everything whose name this client (FrameXML), the hand-written ModernUI
# templates (90_Templates.xml) or an earlier file already defines left out, and Lua (<Script>) and
# <Include> elements removed (their Lua is imported by 96_BlizzardShared.lua). Usage:
#   python3 gen_templates.py <Interface/AddOns> <FrameXML dir of 3.3.5> <out.xml> <spec>...
# where a spec is an AddOn name or AddOn/File.toc.
import os, re, sys
import xml.etree.ElementTree as ET

src, framexml, out = sys.argv[1], sys.argv[2], sys.argv[3]
here = os.path.dirname(os.path.abspath(__file__))

def strip_ns(tree):
    for el in tree.iter():
        if isinstance(el.tag, str) and '}' in el.tag:
            el.tag = el.tag.split('}', 1)[1]

def parse(path):
    text = open(path, encoding='utf-8-sig', errors='replace').read()
    try:
        root = ET.fromstring(text)
    except ET.ParseError as e:
        print('skip (does not parse):', path, e)
        return None
    strip_ns(root)
    return root

existing = set()
for path in [os.path.join(framexml, f) for f in os.listdir(framexml) if f.lower().endswith('.xml')] + [os.path.join(here, '..', '90_Templates.xml')]:
    root = parse(path)
    if root is None:
        continue
    for el in root:
        name = el.get('name')
        if name:
            existing.add(name.lower())

kept, skipped = [], 0
seen_files = set()

def add_xml(path):
    global skipped
    if not os.path.exists(path) or path in seen_files:
        return
    seen_files.add(path)
    root = parse(path)
    if root is None:
        return
    base = os.path.dirname(path)
    for el in list(root):
        tag = el.tag
        if tag == 'Include':
            add_xml(os.path.normpath(os.path.join(base, el.get('file', '').replace('\\', '/'))))
            continue
        if tag == 'Script':
            continue
        name = el.get('name')
        if not name or el.get('intrinsic') == 'true':
            skipped += 1
            continue
        if tag not in ('Font', 'FontFamily') and el.get('virtual') != 'true':
            skipped += 1
            continue
        if name.lower() in existing:
            skipped += 1
            continue
        existing.add(name.lower())
        kept.append((os.path.relpath(path, src), el))

for spec in sys.argv[4:]:
    if spec.endswith('.toc'):
        addon = spec.split('/')[0]
        toc = os.path.join(src, spec)
    else:
        addon = spec
        toc = os.path.join(src, addon, addon + '.toc')
    for line in open(toc, encoding='utf-8-sig'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        if 'AllowLoad Glue' in line and 'AllowLoad Game' not in line:
            continue
        entry = line.split()[0].replace('[Family]', 'Classic')
        if entry.lower().endswith('.xml'):
            add_xml(os.path.join(src, addon, entry.replace('\\', '/')))

ui = ET.Element('Ui')
last = None
for rel, el in kept:
    if rel != last:
        ui.append(ET.Comment(' ' + rel.replace('--', '-') + ' '))
        last = rel
    el.tail = '\n\t'
    ui.append(el)
body = ET.tostring(ui, encoding='unicode')
with open(out, 'w', encoding='utf-8') as f:
    f.write('<!-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by tools/gen_templates.py.\n')
    f.write("     Blizzard's shared fonts and templates from the Wrath Classic client that this client lacks. -->\n")
    f.write(body + '\n')
print(len(kept), 'kept', skipped, 'skipped')
