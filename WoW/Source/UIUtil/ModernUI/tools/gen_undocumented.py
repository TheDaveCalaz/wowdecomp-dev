# Builds 94_UndocumentedAPI.lua: functions that Blizzard's own UI code (and AddOn code given here) calls but the
# API documentation does not list, which this client may lack: global functions (EJ_GetInstanceInfo, ...) and
# functions of C_ namespaces (C_Heirloom.PlayerHasHeirloom, C_WowTokenPublic.GetCurrentMarketPrice, ...).
# Names the scanned Lua defines itself are left out; at run time each is set only where nothing exists, so the
# client's own functions, hand-written ones and the documented surface always win.
# Usage: python3 gen_undocumented.py <out.lua> <Lua dir> [<Lua dir>...]
import re, glob, os, sys
MUI = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def strip(s):
    s = re.sub(r'--\[(=*)\[.*?\]\1\]', '', s, flags=re.S)
    s = re.sub(r'\[(=*)\[.*?\]\1\]', '""', s, flags=re.S)
    s = re.sub(r'"(?:\\.|[^"\\\n])*"', '""', s)
    s = re.sub(r"'(?:\\.|[^'\\\n])*'", "''", s)
    return re.sub(r'--[^\n]*', '', s)

surface = open(MUI + '/95_ApiSurface.lua').read()
documented = set(re.findall(r'^"([^"]*)","([^"]*)",', surface, re.M))
documented_globals = {n for ns, n in documented if ns == ''}

defined, ns_defined = set(), set()
calls, ns_calls = set(), set()
for root in sys.argv[2:]:
    for f in glob.glob(root + '/**/*.lua', recursive=True):
        if 'APIDocumentation' in f:
            continue
        s = strip(open(f, encoding='utf-8', errors='replace').read())
        defined.update(re.findall(r'\bfunction\s+([A-Za-z_]\w*)\s*\(', s))
        defined.update(re.findall(r'^\s*([A-Za-z_]\w*)\s*=[^=]', s, re.M))
        defined.update(re.findall(r'\blocal\s+function\s+([A-Za-z_]\w*)', s))
        for names in re.findall(r'\blocal\s+([A-Za-z_][\w\s,]*?)\s*=', s):
            defined.update(n.strip() for n in names.split(','))
        ns_defined.update(re.findall(r'\bfunction\s+(C_\w+)[.:](\w+)\s*\(', s))
        ns_defined.update(re.findall(r'\b(C_\w+)\.(\w+)\s*=[^=]', s))
        calls.update(re.findall(r'(?<![.:\w])([A-Z][A-Za-z0-9_]+)\s*\(', s))
        ns_calls.update(re.findall(r'(?<![.:\w])(C_[A-Za-z0-9_]+)\.([A-Z]\w*)\b(?!\s*=[^=])', s))

old = open(MUI + '/94_UndocumentedAPI.lua').read() if os.path.exists(MUI + '/94_UndocumentedAPI.lua') else ''
old_globals = set(re.findall(r'"([A-Za-z_]\w*)"', old[old.find('local LIST'):old.find('}', old.find('local LIST'))]))
globals_ = sorted((calls - defined - documented_globals) | old_globals)
spaces = sorted(k for k in ns_calls if k not in documented and k not in ns_defined)

def wrap(items):
    lines, line = [], ''
    for item in items:
        if len(line) + len(item) > 112:
            lines.append(line)
            line = ''
        line += item
    if line:
        lines.append(line)
    return lines

out = ['-- ModernUI: built into the client (not in the original 3.3.5a). GENERATED by tools/gen_undocumented.py.',
       "-- Functions Blizzard's own interface code (Wrath Classic and retail) calls that are not in the API",
       '-- documentation, globals and C_ namespace functions. Each answers as a client with nothing to report would:',
       '-- GetNum... 0, Is/Has/Can/Should... false, anything else nothing. Real implementations always win.', '',
       'local LIST = {'] + wrap('"%s",' % n for n in globals_) + ['}', 'local NAMESPACED = {'] + \
      wrap('"%s","%s",' % k for k in spaces) + ['}', '''local function zero() return 0 end
local function no() return false end
local function nothing() end
local function answer(name)
	if name:find("^GetNum") then
		return zero
	elseif name:find("^Is") or name:find("^Has") or name:find("^Can") or name:find("^Should") or name:find("^Player[HC]a") then
		return no
	end
	return nothing
end
for _, name in ipairs(LIST) do
	if rawget(_G, name) == nil then
		_G[name] = answer(name)
	end
end
for i = 1, #NAMESPACED, 2 do
	local ns, name = NAMESPACED[i], NAMESPACED[i + 1]
	local space = rawget(_G, ns)
	if space == nil then
		space = {}
		_G[ns] = space
	end
	if type(space) == "table" and rawget(space, name) == nil then
		space[name] = answer(name)
	end
end
''']
open(sys.argv[1], 'w').write('\n'.join(out))
print(len(globals_), 'globals,', len(spaces), 'namespaced functions,', len({k[0] for k in spaces}), 'namespaces')
